export type Message = keyof typeof traditionalChinese;
export type Variables = Record<string, string | number>;
export type Translator = (message: Message, variables?: Variables) => string;

/** Choose the first supported language in browser preference order. */
export function browserLocale(languages: readonly string[]): Locale {
  for (const language of languages) {
    if (/^zh(?:-|$)/i.test(language)) return "zh-TW";
    if (/^en(?:-|$)/i.test(language)) return "en";
  }
  return "en";
}

export function isLocale(value: unknown): value is Locale {
  return value === "en" || value === "zh-TW";
}

/** Saved explicit choice wins; blocked storage behaves like a first visit. */
export function initialLocale(storage: Pick<Storage, "getItem"> | undefined, languages: readonly string[]): Locale {
  try {
    const saved = storage?.getItem(LOCALE_KEY);
    if (isLocale(saved)) return saved;
  } catch { /* Browser privacy settings may disable storage in embedded panels. */ }
  return browserLocale(languages);
}

export function rememberLocale(storage: Pick<Storage, "setItem"> | undefined, locale: Locale): void {
  try { storage?.setItem(LOCALE_KEY, locale); } catch { /* Selection still applies for this panel session. */ }
}

/** Interpolate plain strings once; React escapes these values when rendering. */
export function translate(locale: Locale, message: Message, variables: Variables = {}): string {
  const text = locale === "zh-TW" ? traditionalChinese[message] : message;
  return text.replace(/\{(\w+)\}/g, (match, name: string) => Object.hasOwn(variables, name) ? String(variables[name]) : match);
}
