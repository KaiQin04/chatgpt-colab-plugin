/**
 * Build ui/ into one self-contained HTML document and write it as a TS module
 * (lib/notebook/ui-bundle.generated.ts) so the Worker and Node tests can import
 * it without loaders. The module is ignored by Git and generated before tests,
 * typechecking, development and production builds. Run npm run install:ci to install both
 * lockfiles, then npm run build:ui to generate it explicitly.
 */
import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { parseArgs } from "node:util";
import { build } from "vite";

const root = fileURLToPath(new URL("..", import.meta.url));
const uiDir = join(root, "ui");
const outDir = join(root, ".ui-build");

/** Hash of every ui/ source file plus the shared modules the UI imports. */
export function uiSourceHash() {
  const files = [];
  const walk = (dir) => {
    for (const name of readdirSync(dir).sort()) {
      if (name === "node_modules") continue;
      const path = join(dir, name);
      if (statSync(path).isDirectory()) walk(path); else files.push(path);
    }
  };
  walk(uiDir);
  files.push(join(root, "lib/notebook/client.ts"), join(root, "lib/notebook/contract.ts"), join(root, "lib/notebook/png.ts"), join(root, "lib/notebook/types.ts"));
  const hash = createHash("sha256");
  for (const path of files) hash.update(relative(root, path)).update("\0").update(readFileSync(path)).update("\0");
  return hash.digest("hex");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const { values } = parseArgs({ options: { check: { type: "boolean", default: false } } });
  if (!existsSync(join(uiDir, "node_modules"))) {
    console.error("UI dependencies missing: run `npm run install:ci` (or install both lockfiles explicitly).");
    process.exit(1);
  }
  await build({ configFile: join(uiDir, "vite.config.ts"), logLevel: "warn" });
  const js = readFileSync(join(outDir, "app.js"), "utf8").replaceAll("</script", "<\\/script");
  const cssFile = readdirSync(outDir).find((name) => name.endsWith(".css"));
  const css = cssFile ? readFileSync(join(outDir, cssFile), "utf8").replaceAll("</style", "<\\/style") : "";
  const html = `<!doctype html><html lang="zh-Hant-TW"><head><meta charset="utf-8">` +
    `<meta name="viewport" content="width=device-width,initial-scale=1"><title>Colab Notebook</title>` +
    `<style>${css}</style></head><body><div id="root"></div>` +
    `<script>window.__CCM_MODE__="__CCM_MODE__";window.__CCM_SITE_ORIGIN__="__CCM_SITE_ORIGIN__";</script>` +
    `<script>${js}</script></body></html>`;
  const generated = `/* Generated by scripts/build-notebook-ui.mjs. Do not edit. */\n` +
    `export const NOTEBOOK_UI_SOURCE_HASH = ${JSON.stringify(uiSourceHash())};\n` +
    `export const NOTEBOOK_UI_TEMPLATE = ${JSON.stringify(html)};\n`;
  const generatedPath = join(root, "lib/notebook/ui-bundle.generated.ts");
  if (values.check) {
    if (!existsSync(generatedPath) || readFileSync(generatedPath, "utf8") !== generated) {
      console.error("Generated notebook UI differs from a fresh source build. Review source/lockfile changes and rerun npm run check:ui.");
      process.exitCode = 1;
    } else {
      console.log(`Notebook UI reproduced byte-for-byte (${Buffer.byteLength(html)} bytes).`);
    }
  } else {
    writeFileSync(generatedPath, generated);
    console.log(`notebook UI: ${Buffer.byteLength(html)} bytes`);
  }
}
